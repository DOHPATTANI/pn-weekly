import fs from 'node:fs/promises';
import http from 'node:http';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';

// Isolate shared shell interactions; full app/data regression remains owned by tools.mjs qa.
const html = await fs.readFile('index.html', 'utf8');
const css = await fs.readFile('styles.css', 'utf8');
const js = await fs.readFile('src/sidebar.js', 'utf8');
const server = http.createServer((req, res) => {
  const file = req.url.split('?')[0];
  res.setHeader('Content-Type', file === '/styles.css' ? 'text/css' : file === '/app.js' ? 'text/javascript' : 'text/html');
  res.end(file === '/styles.css' ? css : file === '/app.js' ? js : html);
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({headless:true,...(process.env.PN_CHROMIUM ? {executablePath:process.env.PN_CHROMIUM} : {})});
const base = 'http://127.0.0.1:' + server.address().port;
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  const sidebar=page.locator('#app-sidebar'),toggle=page.locator('#sidebar-toggle'),search=page.locator('#sidebar-search-input');
  await page.waitForFunction(()=>document.querySelector('#app-sidebar').dataset.interactionMounted);
  assert.equal(await sidebar.evaluate(el=>el.classList.contains('is-collapsed')),false);
  await toggle.click();
  await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===80);
  assert.equal(await toggle.getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('.nav-text').first().isVisible(),false);
  assert.equal(await page.locator('.nav-header').isVisible(),false);
  assert.equal(await page.locator('#pending-count').isVisible(),false);
  assert.equal(await page.locator('.brand-details').isVisible(),false);
  const centers=await page.locator('.sidebar .nav-icon').evaluateAll(els=>els.map(el=>el.getBoundingClientRect().x+el.getBoundingClientRect().width/2));
  assert(Math.max(...centers)-Math.min(...centers)<1,'icons have a common centerline');
  assert.equal(await search.isVisible(),false);
  assert.equal(await page.evaluate(()=>localStorage.getItem('pn-weekly-sidebar-collapsed')),'true');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#app-sidebar').classList.contains('is-collapsed'));
  await page.locator('#sidebar-search-open').click();
  assert.equal(await sidebar.evaluate(el=>el.classList.contains('is-collapsed')),false);
  assert.equal(await search.evaluate(el=>document.activeElement===el),true);
  await search.fill('ทะเบียน');
  assert.equal(await page.locator('.sidebar [data-view]:visible').count(),2);
  await search.fill('not-a-menu');assert.equal(await page.locator('#sidebar-no-results').isVisible(),true);
  await page.locator('#sidebar-search-clear').click();assert.equal(await page.locator('.sidebar [data-view]:visible').count(),9);
  await toggle.click();await page.keyboard.press('Control+k');
  assert.equal(await search.evaluate(el=>document.activeElement===el),true);
  await toggle.click();await page.keyboard.press('Meta+k');
  assert.equal(await search.evaluate(el=>document.activeElement===el),true);
  await page.locator('#modal').evaluate(el=>el.showModal());
  await page.keyboard.press('Control+k');assert.equal(await search.evaluate(el=>document.activeElement===el),false);
  await page.locator('#modal').evaluate(el=>el.close());
  await toggle.click();
  await page.setViewportSize({width:375,height:812});
  await page.waitForFunction(()=>!document.querySelector('.sidebar').classList.contains('is-collapsed'));
  await page.keyboard.press('Control+k');
  assert.equal(await sidebar.evaluate(el=>el.classList.contains('open')),true);
  assert.equal(await search.evaluate(el=>document.activeElement===el),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.keyboard.press('Escape');assert.equal(await sidebar.evaluate(el=>el.classList.contains('open')),false);
  await page.setViewportSize({width:1440,height:1000});
  // Opening search changes the saved preference to expanded.
  await page.waitForFunction(()=>!document.querySelector('.sidebar').classList.contains('is-collapsed'));
  await context.close();
  const restricted=await browser.newContext({viewport:{width:1200,height:850},reducedMotion:'reduce'});
  await restricted.addInitScript(()=>{Storage.prototype.setItem=()=>{throw new Error('storage unavailable')};Storage.prototype.getItem=()=>{throw new Error('storage unavailable')};});
  const reduced=await restricted.newPage();reduced.on('pageerror',e=>errors.push(e.message));await reduced.goto(base);
  await reduced.evaluate(()=>{window.sidebarResizeEvents=0;window.addEventListener('resize',()=>window.sidebarResizeEvents++);});
  await reduced.locator('#sidebar-toggle').click();
  await reduced.waitForFunction(()=>window.sidebarResizeEvents>0);
  assert.equal(await reduced.locator('.sidebar').evaluate(el=>el.classList.contains('is-collapsed')),true);
  assert.equal(await reduced.locator('.sidebar').evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
  await fs.mkdir('work/sidebar',{recursive:true});
  await reduced.screenshot({path:'work/sidebar/collapsed.png'});
  await reduced.locator('#sidebar-search-open').click();await reduced.screenshot({path:'work/sidebar/expanded.png'});
  assert.deepEqual(errors,[]);
  console.log('Sidebar passed: persistence, 80px rail, labels/badges, aligned icons, search/clear/no-results, Ctrl/Cmd+K, modal guard, mobile drawer, reduced motion, storage failure.');
  await restricted.close();
} finally {await browser.close();await new Promise(resolve=>server.close(resolve));}
